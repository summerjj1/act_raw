class Backbone(BackboneBase):
    """ResNet backbone with frozen BatchNorm."""
    def __init__(self, name: str,
                 train_backbone: bool,
                 return_interm_layers: bool,
                 dilation: bool,
                 image_channels: int = 3):
        backbone = getattr(torchvision.models, name)(
            replace_stride_with_dilation=[False, False, dilation],
            pretrained=is_main_process(), norm_layer=FrozenBatchNorm2d) # pretrained # TODO do we want frozen batch_norm??
        if image_channels != 3:
            if image_channels != 4:
                raise ValueError(
                    f'Only RGB (3) or BGGR Bayer planes (4) are supported; '
                    f'got image_channels={image_channels}'
                )
            rgb_conv = backbone.conv1
            raw_conv = nn.Conv2d(
                4,
                rgb_conv.out_channels,
                kernel_size=rgb_conv.kernel_size,
                stride=rgb_conv.stride,
                padding=rgb_conv.padding,
                bias=False,
            )
            with torch.no_grad():
                # Input order is [B, G1, G2, R]. Splitting the pretrained
                # green kernel in half preserves the original RGB response
                # when the two green planes are similar.
                raw_conv.weight[:, 0].copy_(rgb_conv.weight[:, 2])
                raw_conv.weight[:, 1].copy_(0.5 * rgb_conv.weight[:, 1])
                raw_conv.weight[:, 2].copy_(0.5 * rgb_conv.weight[:, 1])
                raw_conv.weight[:, 3].copy_(rgb_conv.weight[:, 0])
            backbone.conv1 = raw_conv
        num_channels = 512 if name in ('resnet18', 'resnet34') else 2048
        super().__init__(backbone, train_backbone, num_channels, return_interm_layers)


class Joiner(nn.Sequential):
    def __init__(self, backbone, position_embedding):
        super().__init__(backbone, position_embedding)

    def forward(self, tensor_list: NestedTensor):
        xs = self[0](tensor_list)
        out: List[NestedTensor] = []
        pos = []
        for name, x in xs.items():
            out.append(x)
            # position encoding
            pos.append(self[1](x).to(x.dtype))

        return out, pos


def build_backbone(args):
    position_embedding = build_position_encoding(args)
    train_backbone = args.lr_backbone > 0
    return_interm_layers = args.masks
    backbone = Backbone(
        args.backbone,
        train_backbone,
        return_interm_layers,
        args.dilation,
        image_channels=getattr(args, 'image_channels', 3),
    )
    model = Joiner(backbone, position_embedding)
    model.num_channels = backbone.num_channels
    return model
